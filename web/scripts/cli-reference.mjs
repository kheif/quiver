// Writes the CLI reference page from the help text of the quiver binary, so
// the website cannot drift from the commands.
//
//   npm run cli-reference                      builds quiver from ../cmd/quiver
//   QUIVER_BIN=/path/to/quiver npm run cli-reference
//
// The Pages workflow runs it before every build.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const out = resolve(here, '../src/content/docs/docs/reference/cli.md');

// Commands generated by cobra or documented elsewhere.
const skip = new Set(['help', 'completion bash', 'completion fish', 'completion powershell', 'completion zsh']);

/** Splits cobra help output into its description and sections. */
export function parseHelp(text) {
	const lines = text.replace(/\r/g, '').split('\n');
	const sections = { description: [] };
	let current = 'description';
	for (const line of lines) {
		const header = /^([A-Z][A-Za-z ]+):$/.exec(line);
		if (header) {
			current = header[1].toLowerCase();
			sections[current] = [];
			continue;
		}
		if (/^Use ".*" for more information/.test(line)) continue;
		sections[current].push(line);
	}
	const trim = (ls) => {
		const copy = [...ls];
		while (copy.length && !copy[0].trim()) copy.shift();
		while (copy.length && !copy.at(-1).trim()) copy.pop();
		return copy;
	};
	const dedent = (ls) => ls.map((l) => l.replace(/^ {2}/, ''));
	return {
		description: trim(sections.description),
		usage: dedent(trim(sections.usage ?? [])),
		examples: dedent(trim(sections.examples ?? [])),
		commands: trim(sections['available commands'] ?? [])
			.map((l) => /^\s+(\S+)\s+(.*)$/.exec(l))
			.filter(Boolean)
			.map(([, name, summary]) => ({ name, summary })),
		flags: trim(sections.flags ?? [])
			.map((l) => /^\s+(?:(-\w), )?(--[\w-]+)(?: (\w+))?\s{2,}(.*)$/.exec(l))
			.filter(Boolean)
			.map(([, short, long, type, desc]) => ({ short, long, type, desc }))
			.filter((f) => f.long !== '--help'),
	};
}

const escape = (s) => s.replace(/[<>*_`\\|[\]]/g, (c) => `\\${c}`);

/** Turns help text into Markdown: paragraphs, and indented lines as code. */
export function descriptionToMarkdown(lines) {
	const blocks = [];
	let para = [];
	let code = [];
	const flush = () => {
		if (para.length) blocks.push(escape(para.join(' ')));
		if (code.length) blocks.push('```text\n' + code.join('\n') + '\n```');
		para = [];
		code = [];
	};
	for (const line of lines) {
		if (!line.trim()) {
			flush();
		} else if (/^\s{2,}/.test(line)) {
			if (para.length) flush();
			code.push(line.replace(/^ {2}/, ''));
		} else {
			if (code.length) flush();
			para.push(line.trim());
		}
	}
	flush();
	return blocks.join('\n\n');
}

function renderCommand(path, help) {
	const parts = [`## quiver ${path}`.trimEnd(), '', descriptionToMarkdown(help.description)];
	if (help.usage.length) parts.push('', '```sh\n' + help.usage.join('\n') + '\n```');
	if (help.flags.length) {
		parts.push('', '| Flag | Description |', '| --- | --- |');
		for (const f of help.flags) {
			const name = [f.short, f.long].filter(Boolean).join(', ') + (f.type ? ` <${f.type}>` : '');
			parts.push(`| \`${name}\` | ${escape(f.desc)} |`);
		}
	}
	if (help.examples.length) {
		parts.push('', '**Examples**', '', '```sh\n' + help.examples.join('\n') + '\n```');
	}
	return parts.join('\n');
}

function main() {
	let bin = process.env.QUIVER_BIN;
	let tmp;
	if (!bin) {
		tmp = mkdtempSync(join(tmpdir(), 'quiver-cli-'));
		bin = join(tmp, process.platform === 'win32' ? 'quiver.exe' : 'quiver');
		execFileSync('go', ['build', '-o', bin, './cmd/quiver'], { cwd: root, stdio: 'inherit' });
	}
	const env = {
		...process.env,
		NO_COLOR: '1',
		QUIVER_NO_UPDATE_CHECK: '1',
		QUIVER_HOME: tmp ?? mkdtempSync(join(tmpdir(), 'quiver-home-')),
	};
	const help = (args) => parseHelp(execFileSync(bin, [...args, '--help'], { env, encoding: 'utf8' }));

	const sections = [];
	const walk = (args) => {
		const h = help(args);
		const path = args.join(' ');
		if (!skip.has(path)) sections.push(renderCommand(path, h));
		for (const c of h.commands) walk([...args, c.name]);
	};
	const top = help([]);
	for (const c of top.commands) walk([c.name]);

	const page = `---
title: CLI reference
description: Every quiver command with its flags and examples, generated from the help text of the binary.
editUrl: false
tableOfContents:
  maxHeadingLevel: 2
---

<!-- Generated by web/scripts/cli-reference.mjs from \`quiver <command> --help\`. Do not edit by hand. -->

This page is generated from the help text of \`quiver\` on the main branch, which can be ahead of the latest release; the guides mark such commands **Next release**. Run \`quiver help <command>\` for the same text in your terminal.

Every command takes \`-v\`, \`--verbose\` to print more details, and \`-h\`, \`--help\`.

${sections.join('\n\n')}
`;
	writeFileSync(out, page);
	if (tmp) rmSync(tmp, { recursive: true, force: true });
	console.log(`wrote ${out} (${sections.length} commands)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
